import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const id = process.argv[2];
if (!id || !/^[a-z][a-z0-9-]{1,39}$/.test(id)) {
  console.error('Usage: node scripts/create-adapter.mjs <marketplace-id>  (lowercase, a-z/0-9/-)');
  process.exit(1);
}

const root = process.cwd();
const dir = join(root, 'server', 'adapters', 'marketplaces', id);
if (existsSync(dir)) {
  console.error(`Adapter directory already exists: ${dir}`);
  process.exit(1);
}
mkdirSync(dir, { recursive: true });
mkdirSync(join(dir, 'tests', 'fixtures'), { recursive: true });

const label = id.charAt(0).toUpperCase() + id.slice(1);

writeFileSync(join(dir, 'adapter.ts'), `import type { MarketplaceAdapter, AdapterHealth, AdapterSearchParams, NormalizedListing } from '../../core/types.js';
import { SourceError } from '../../core/types.js';

/**
 * ${label} adapter.
 *
 * TODO: implement search() and healthCheck(). Declare only capabilities you
 * actually support in adapterCapabilities.
 */
export class ${label}Adapter implements MarketplaceAdapter {
  readonly id = '${id}';
  readonly label = '${label}';
  readonly mode = 'live' as const;
  readonly markets: string[] = [];
  readonly icon = 'search';
  readonly description = '${label} marketplace adapter (scaffold).';
  readonly auth = 'Public search page · no key';
  readonly envVars: string[] = ['ENABLE_${id.toUpperCase().replace(/-/g, '_')}_ADAPTER'];
  readonly capabilities: string[] = ['Public web search'];
  readonly docsUrl = '';
  readonly configFields = [];

  readonly adapterCapabilities = {
    search: true, pagination: false, detail: false, categories: false,
    locationFilter: false, conditionFilter: false, priceFilter: false,
    sort: false, images: false, sellerInfo: false, publishedDate: false,
  };

  isEnabled(): boolean { return true; }
  disabledReason(): string | null { return null; }

  async healthCheck(): Promise<AdapterHealth> {
    return { ok: false, latencyMs: 0, message: 'Not implemented yet.' };
  }

  async search(_params: AdapterSearchParams): Promise<NormalizedListing[]> {
    throw new SourceError('${label} adapter not implemented', 'UPSTREAM');
  }
}
`);

writeFileSync(join(dir, 'mapper.ts'), `// Map ${label} raw responses into NormalizedListing. Keep source-specific fields here.
export function mapToListing(raw: unknown): unknown {
  return raw;
}
`);

writeFileSync(join(dir, 'README.md'), `# ${label} adapter

Scaffold generated by \`pnpm adapter:create ${id}\`.

## Status
Scaffold only — not implemented. Set \`adapter_status\` in the registry accordingly.

## Implementation checklist
- [ ] search()
- [ ] healthCheck()
- [ ] pagination
- [ ] detail retrieval
- [ ] tests + fixtures
`);

writeFileSync(join(dir, 'tests', 'search.test.ts'), `import { describe, it } from 'node:test';
import assert from 'node:assert/strict';

describe('${id} adapter', () => {
  it('scaffold exists', () => {
    assert.ok(true);
  });
});
`);

console.log(`Created adapter scaffold at ${dir}`);
console.log(`Next: implement search()/healthCheck(), register in server/core/registry.ts, update server/registry/marketplaces.json.`);
